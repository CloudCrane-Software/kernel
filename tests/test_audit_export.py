async def test_ddl_applies_twice_idempotent(db: Database) -> None:
    """0004 must be re-runnable (apply_schema runs on every startup)."""
    sql = (REPO / "ops" / "sql" / "0004_audit_export.sql").read_text(encoding="utf-8")
    async with db.pool.acquire() as conn:
        await conn.execute(sql)  # 2nd application (db fixture already applied once)
        await conn.execute(sql)  # 3rd application
        singletons = await conn.fetchval("SELECT count(*) FROM audit_export_state")
        events = await conn.fetchval("SELECT count(*) FROM audit_events")
    assert singletons == 1, "singleton cursor row must never duplicate"
    assert events == 0


async def test_fresh_cursor_is_empty(db: Database) -> None:
    exporter = _exporter(db, _fake_restate_client([]), FakePublisher())
    assert await exporter.load_cursor() == (None, "")


# ----------------------------------------------------------------- exporter
async def test_exporter_exports_and_advances_cursor(
    db: Database, restate: httpx.AsyncClient
) -> None:
    await _reset(db)
    publisher = FakePublisher()
    exporter = _exporter(db, restate, publisher)

    assert await exporter.poll_once() == 3
    assert [key for key, _ in publisher.events] == ["inv_0001", "inv_0002", "inv_0003"]
    for key, event in publisher.events:
        assert event["event_type"] == EVENT_TYPE
        assert event["exported_at"] == _FIXED_NOW.isoformat()
        assert event["invocation"]["id"] == key

    snapshot = await _table_snapshot(db)
    assert len(snapshot) == 3
    assert snapshot[0][:4] == ("inv_0001", "executor", "notify", "completed")
    assert snapshot[1][:4] == ("inv_0002", "executor", "run", "running")
    assert snapshot[2][:4] == ("inv_0003", "reconciler", "probe", "scheduled")
    # created_at normalized from the Z-suffix strings to aware datetimes
    assert snapshot[0][4] == datetime(2026, 9, 17, 8, 0, 0, 100000, tzinfo=UTC)
    assert snapshot[0][6] == _FIXED_NOW

    # cursor advanced to (last created_at, last id) — same-ms tiebreaker held
    cursor_ts, cursor_id = await exporter.load_cursor()
    assert cursor_ts == datetime(2026, 9, 17, 8, 0, 0, 500000, tzinfo=UTC)
    assert cursor_id == "inv_0003"

    # second poll: the cursor predicate filters everything out
    assert await exporter.poll_once() == 0
    assert len(publisher.events) == 3


async def test_reexport_of_same_records_produces_no_duplicates(
    db: Database, restate: httpx.AsyncClient
) -> None:
    await _reset(db)
    publisher = FakePublisher()
    exporter = _exporter(db, restate, publisher)
    await exporter.poll_once()
    snapshot = await _table_snapshot(db)
    assert len(snapshot) == 3

    # simulate cursor loss (restored from an old backup): full re-export
    async with db.pool.acquire() as conn:
        await conn.execute(
            "UPDATE audit_export_state SET cursor_created_at = NULL, cursor_invocation_id = ''"
        )
    assert await exporter.poll_once() == 3
    assert len(publisher.events) == 6  # re-published to Kafka...
    assert await _table_snapshot(db) == snapshot  # ...but PG rows identical, no duplicates
    async with db.pool.acquire() as conn:
        count = await conn.fetchval("SELECT count(*) FROM audit_events")
    assert count == 3


# ----------------------------------------------------------------- consumer
async def test_consumer_replay_rebuilds_identical_table(
    db: Database, restate: httpx.AsyncClient
) -> None:
    await _reset(db)
    publisher = FakePublisher()
    await _exporter(db, restate, publisher).poll_once()
    original = await _table_snapshot(db)
    assert len(original) == 3

    # database lost; replay the published events from earliest offset
    async with db.pool.acquire() as conn:
        await conn.execute("TRUNCATE audit_events")
    source = FakeSource([event for _, event in publisher.events])
    consumer = AuditConsumer(db, source)
    assert await consumer.poll_once() == 3
    assert source.commits == 1, "offsets commit only after the batch applied"
    assert await _table_snapshot(db) == original

    # a full second replay (earliest offset again) is still idempotent
    replay = FakeSource([event for _, event in publisher.events])
    assert await AuditConsumer(db, replay).poll_once() == 3
    assert await _table_snapshot(db) == original


async def test_consumer_replay_all_drains_and_stops(db: Database) -> None:
    await _reset(db)
    events = [build_event(row, exported_at=_FIXED_NOW) for row in _INVOCATIONS[:2]]
    consumer = AuditConsumer(db, FakeSource(events))
    assert await consumer.replay_all(idle_rounds=2) == 2
    async with db.pool.acquire() as conn:
        count = await conn.fetchval("SELECT count(*) FROM audit_events")
    assert count == 2


