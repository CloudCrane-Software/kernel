def _row_key(row: dict[str, Any]) -> tuple[datetime, str]:
    ts = parse_ts(row["created_at"])
    assert ts is not None
    return ts, str(row["id"])


def _fake_restate_client(rows: list[dict[str, Any]]) -> httpx.AsyncClient:
    """MockTransport speaking the live admin /query protocol, including the
    cursor predicate semantics (strictly-after (created_at, id) ordering)."""

    def handler(request: httpx.Request) -> httpx.Response:
        assert request.url.path == "/query", "the live admin API has no other read path"
        assert request.headers.get("Accept") == "application/json"
        sql = json.loads(request.content.decode("utf-8"))["query"]
        selected = rows
        if m := _CURSOR_RE.search(sql):
            cursor = (datetime.fromisoformat(m.group(1)), m.group(3))
            selected = [r for r in rows if _row_key(r) > cursor]
        return httpx.Response(200, json={"rows": selected})

    return httpx.AsyncClient(transport=httpx.MockTransport(handler))


class FakePublisher:
    """In-memory audit event publisher (records every publish)."""

    def __init__(self) -> None:
        self.events: list[tuple[str, dict[str, Any]]] = []

    async def start(self) -> None: ...

    async def stop(self) -> None: ...

    async def publish(self, key: str, event: dict[str, Any]) -> None:
        self.events.append((key, event))


class FakeSource:
    """In-memory audit event source (drains a fixed event log)."""

    def __init__(self, events: list[dict[str, Any]]) -> None:
        self._pending = list(events)
        self.commits = 0

    async def start(self) -> None: ...

    async def stop(self) -> None: ...

    async def getmany(self, *, timeout_ms: int, max_records: int) -> list[dict[str, Any]]:
        del timeout_ms
        batch = self._pending[:max_records]
        del self._pending[:max_records]
        return batch

    async def commit(self) -> None:
        self.commits += 1


@pytest_asyncio.fixture
async def restate() -> AsyncIterator[httpx.AsyncClient]:
    client = _fake_restate_client(_INVOCATIONS)
    yield client
    await client.aclose()


def _exporter(db: Database, restate: httpx.AsyncClient, publisher: FakePublisher) -> AuditExporter:
    return AuditExporter(
        db,
        RestateAdminClient("http://restate.local", client=restate),
        publisher,
        exported_at_clock=lambda: _FIXED_NOW,
    )


async def _table_snapshot(db: Database) -> list[tuple[Any, ...]]:
    """Full-row projection of audit_events (asyncpg decodes timestamptz to
    UTC-aware datetimes, so values compare by instant, not by text)."""
    async with db.pool.acquire() as conn:
        rows = await conn.fetch(
            """SELECT invocation_id, service_name, handler_name, status,
                      created_at, raw::text, exported_at
               FROM audit_events ORDER BY invocation_id"""
        )
    return [tuple(r) for r in rows]


async def _reset(db: Database) -> None:
    async with db.pool.acquire() as conn:
        await conn.execute("TRUNCATE audit_events")
        await conn.execute(
            "UPDATE audit_export_state SET cursor_created_at = NULL, cursor_invocation_id = ''"
        )


