def test_parse_ts_shapes() -> None:
    assert parse_ts("2026-09-17T08:00:00.123Z") == datetime(
        2026, 9, 17, 8, 0, 0, 123000, tzinfo=UTC
    )
    assert parse_ts("2026-09-17 08:00:00+00:00") == datetime(2026, 9, 17, 8, tzinfo=UTC)
    assert parse_ts(0) == datetime(1970, 1, 1, tzinfo=UTC)
    assert parse_ts(86400000) == datetime(1970, 1, 2, tzinfo=UTC)
    assert parse_ts(None) is None
    with pytest.raises(ValueError, match="unparseable"):
        parse_ts(object())
