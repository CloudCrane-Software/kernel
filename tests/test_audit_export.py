# The cursor predicate generated by RestateAdminClient.fetch_invocations.
_CURSOR_RE = re.compile(
    r"WHERE created_at > TIMESTAMP '([^']+)' "
    r"OR \(created_at = TIMESTAMP '([^']+)' AND id > '([^']*)'\)"
)

